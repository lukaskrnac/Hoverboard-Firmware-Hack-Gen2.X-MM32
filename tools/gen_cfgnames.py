#!/usr/bin/env python3
"""Writes PinFinder's config name table (HoverBoardMindMotion/PinFinder/cfgnames.h) and cfgfields.json
(for the web console's PinFinder page: copy it next to pinfinder.html) from cfgfields.py.
Run after changing cfgfields.py; the build does not run it (no python needed to build)."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cfgfields import FIELDS, PINS

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "HoverBoardMindMotion", "PinFinder", "cfgnames.h")
lines = ["//generated by tools/gen_cfgnames.py from tools/cfgfields.py: do not edit",
         "//index, 1 = pin, name (PinFinder's config addresses, the same names as tools/mm32config.py)",
         "#define CFG_FIELDS \\"]
for i in sorted(FIELDS):
    name, kind, _ = FIELDS[i]
    lines.append('\tF(%d, %d, "%s") \\' % (i, kind == "pin", name))
lines.append("")
lines.append("#define CFG_FIELD_COUNT %d" % len(FIELDS))
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", os.path.normpath(out), len(FIELDS), "fields")

js = os.path.join(os.path.dirname(os.path.abspath(__file__)), "cfgfields.json")
json.dump({"pins": PINS, "fields": [{"index": i, "name": FIELDS[i][0], "kind": FIELDS[i][1], "meaning": FIELDS[i][2]}
                                    for i in sorted(FIELDS)]}, open(js, "w"), indent=1)
open(js, "a").write("\n")
print("wrote", os.path.normpath(js))
