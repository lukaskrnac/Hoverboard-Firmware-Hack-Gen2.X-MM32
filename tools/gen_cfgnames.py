#!/usr/bin/env python3
"""Writes PinFinder's config name table (HoverBoardMindMotion/PinFinder/cfgnames.h) from cfgfields.py.
Run after changing cfgfields.py; the build does not run it (no python needed to build)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cfgfields import FIELDS

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "HoverBoardMindMotion", "PinFinder", "cfgnames.h")
lines = ["//generated by tools/gen_cfgnames.py from tools/cfgfields.py: do not edit",
         "//index, 1 = pin, name (PinFinder's config addresses, the same names as tools/mm32config.py)",
         "#define CFG_FIELDS \\"]
for i in sorted(FIELDS):
    name, kind, _ = FIELDS[i]
    lines.append('\tF(%d, %d, "%s") \\' % (i, kind == "pin", name))
lines.append("")
lines.append("#define CFG_FIELD_COUNT %d" % len(FIELDS))
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", os.path.normpath(out), len(FIELDS), "fields")
